"""Run one real session in the Docker lab for the dashboard's live demo, streaming its progress.

The session is generated by scripts/generate_lab_runs.py (``--force-tamper`` / ``--force-mutator``),
exactly the code path the experiments use. Afterwards its files are moved out of the experiment
dataset into data/raw/lab_demo so a demo never pollutes data/raw/lab/sessions.
"""

from __future__ import annotations

import os
import shutil
import subprocess
import sys
import time
from pathlib import Path
from typing import Callable

import requests

ROOT = Path(__file__).resolve().parents[2]
LAB = ROOT / "data" / "raw" / "lab"
DEMO = ROOT / "data" / "raw" / "lab_demo"
COLLECTOR = os.environ.get("SECURETRACE_COLLECTOR", "http://127.0.0.1:9000")
STEP_PREFIX = "STEP: "


def lab_available(collector_url: str = COLLECTOR, timeout: float = 1.5) -> bool:
    try:
        return requests.get(f"{collector_url}/health", timeout=timeout).ok
    except requests.RequestException:
        return False


def parse_step(line: str) -> str | None:
    """The progress text of a 'STEP: ...' line, else None."""
    line = line.strip()
    return line[len(STEP_PREFIX):] if line.startswith(STEP_PREFIX) else None


def build_command(segment: str | None, mutator: str, seed: int) -> list[str]:
    cmd = [sys.executable, "-u", "scripts/generate_lab_runs.py", "--runs", "1", "--seed", str(seed)]
    cmd += ["--force-tamper", segment, "--force-mutator", mutator] if segment else ["--force-clean"]
    return cmd


def archive_session(run_id: str, root: Path = ROOT) -> Path:
    """Move everything belonging to `run_id` out of the experiment dataset into data/raw/lab_demo,
    keeping the layout the dashboard loader expects (sessions/, extracted/, pcap/, attacker/)."""
    lab, demo = root / "data" / "raw" / "lab", root / "data" / "raw" / "lab_demo"
    for sub, dest in (("sessions", "sessions"), ("pcap/extracted", "extracted"), ("pcap", "pcap"), ("attacker", "attacker")):
        (demo / dest).mkdir(parents=True, exist_ok=True)
        for f in (lab / sub).glob(f"*{run_id}*"):
            if f.is_file():
                shutil.move(str(f), str(demo / dest / f.name))
    index = lab / "runs_index.yaml"
    if index.exists():  # the generator appended this run; drop it so the dataset index stays truthful
        import yaml

        entries = [e for e in (yaml.safe_load(index.read_text(encoding="utf-8")) or []) if e.get("run_id") != run_id]
        index.write_text(yaml.safe_dump(entries, sort_keys=False), encoding="utf-8")
    return demo / "sessions" / f"{run_id}.json"


def run_live_session(segment: str | None, mutator: str, on_step: Callable[[str], None] | None = None,
                     seed: int | None = None, root: Path = ROOT) -> dict:
    """Run one session, calling `on_step(text)` for each progress line. Returns
    {ok, run_id, steps, manifest_path, error}."""
    seed = seed if seed is not None else int(time.time()) % 100_000
    proc = subprocess.Popen(build_command(segment, mutator, seed), cwd=root, stdout=subprocess.PIPE,
                            stderr=subprocess.STDOUT, text=True, env={**os.environ, "PYTHONUNBUFFERED": "1"})
    steps, run_id, tail = [], None, []
    for line in proc.stdout:  # streamed as the session runs
        tail.append(line.rstrip())
        step = parse_step(line)
        if step:
            steps.append(step)
            if on_step:
                on_step(step)
            if step.startswith("Session saved (") and step.endswith(")"):
                run_id = step[len("Session saved ("):-1]
    code = proc.wait()
    if code != 0 or run_id is None:
        return {"ok": False, "run_id": run_id, "steps": steps, "manifest_path": None,
                "error": "\n".join(tail[-8:]) or f"generator exited with code {code}"}
    manifest = archive_session(run_id, root)
    return {"ok": True, "run_id": run_id, "steps": steps, "manifest_path": manifest, "error": None}
