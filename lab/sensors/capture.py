#!/usr/bin/env python3
"""Per-segment tcpdump capture for one lab session, writing the filenames lab/sensors/extract.py
expects: <pcap-dir>/<run_id>_seg<A|B|C>.pcap

Run inside the sensor container (network_mode: host, so it sees every segment bridge):

    python3 lab/sensors/capture.py start --run-id R --pcap-dir /pcap
    ... run the session (sender/noise/attacker) ...
    python3 lab/sensors/capture.py stop  --run-id R --pcap-dir /pcap

Each segment is captured on BOTH its "_in" and "_out" bridge (see lab/docker-compose.yml) and the
two are merged, so the pcap covers the full segment regardless of whether the attacker relay for
that segment is in pass-through or tamper mode this session.
"""

from __future__ import annotations

import argparse
import json
import os
import signal
import subprocess
import time
from pathlib import Path

PID_SUFFIX = ".capture.pids"

# lab/docker-compose.yml's fixed subnets for each segment's two point-to-point networks. Compose
# gives these bridges autogenerated names (br-<hash>), not names derived from the network key, so
# bridges must be matched by the IP subnet they were given, not by name.
SEGMENT_SUBNETS = {
    "A": ("172.28.11.", "172.28.12."),
    "B": ("172.28.21.", "172.28.22."),
    "C": ("172.28.31.", "172.28.32."),
}


def _bridge_names() -> dict[str, tuple[str, ...]]:
    """Resolve each segment's bridge interface(s) on this host by their compose-assigned subnet."""
    out = subprocess.run(["ip", "-o", "-4", "addr", "show"], capture_output=True, text=True, check=True).stdout
    by_prefix: dict[str, str] = {}
    for line in out.splitlines():
        parts = line.split()
        if len(parts) < 4 or "inet" not in parts:
            continue
        iface, addr = parts[1], parts[3]
        by_prefix[".".join(addr.split(".")[:3]) + "."] = iface

    resolved = {}
    for segment, prefixes in SEGMENT_SUBNETS.items():
        matches = tuple(by_prefix[p] for p in prefixes if p in by_prefix)
        if not matches:
            raise RuntimeError(
                f"No bridge interface found for segment {segment} (subnets {prefixes}; "
                f"seen prefixes: {sorted(by_prefix)}) -- is the lab up with the current topology?"
            )
        resolved[segment] = matches
    return resolved


def start(run_id: str, pcap_dir: Path) -> None:
    pcap_dir.mkdir(parents=True, exist_ok=True)
    bridges = _bridge_names()
    pids = {}
    for segment, ifaces in bridges.items():
        out_path = pcap_dir / f"{run_id}_seg{segment}.pcap"
        procs = [
            subprocess.Popen(["tcpdump", "-i", iface, "-U", "-w", str(pcap_dir / f".{run_id}_seg{segment}_{i}.pcap")])
            for i, iface in enumerate(ifaces)
        ]
        pids[segment] = {
            "pids": [p.pid for p in procs],
            "parts": [str(pcap_dir / f".{run_id}_seg{segment}_{i}.pcap") for i in range(len(ifaces))],
            "out_path": str(out_path),
        }
    (pcap_dir / f".{run_id}{PID_SUFFIX}").write_text(json.dumps(pids))
    time.sleep(1)  # let tcpdump attach before the session's traffic starts
    print(f"capture started for run {run_id}: {list(bridges)}")


def stop(run_id: str, pcap_dir: Path) -> None:
    pid_file = pcap_dir / f".{run_id}{PID_SUFFIX}"
    pids = json.loads(pid_file.read_text())
    for segment, info in pids.items():
        parts, out_path = info["parts"], info["out_path"]
        for pid in info["pids"]:
            try:
                os.kill(pid, signal.SIGTERM)
            except ProcessLookupError:
                pass
        time.sleep(0.5)
        existing = [p for p in parts if Path(p).exists() and Path(p).stat().st_size > 0]
        if len(existing) > 1:
            subprocess.run(["mergecap", "-w", out_path, *existing], check=True)
        elif len(existing) == 1:
            Path(existing[0]).rename(out_path)
        for part in parts:
            Path(part).unlink(missing_ok=True)
        print(f"segment {segment} -> {out_path}")
    pid_file.unlink(missing_ok=True)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("action", choices=["start", "stop"])
    parser.add_argument("--run-id", required=True)
    parser.add_argument("--pcap-dir", type=Path, required=True)
    args = parser.parse_args()
    (start if args.action == "start" else stop)(args.run_id, args.pcap_dir)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
